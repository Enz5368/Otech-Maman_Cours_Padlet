import assert from 'node:assert/strict';
import { unzipSync, strFromU8 } from 'fflate';

export async function testWordPresentation(page, root) {
  await page.evaluate(()=>{
    state.studentClasses = [{ id:'group', title:'5e A', students:['Alice','Bob'] }];
    state.tools = {};
    return WordDocuments.create('lesson');
  });
  await page.waitForFunction(()=>!document.querySelector('[data-word-action]').disabled);
  await page.locator('[contenteditable=true]').focus();
  await page.keyboard.type('Page du chronometre');
  await page.keyboard.press('Enter');
  await page.getByRole('button',{name:'Outils',exact:true}).click();
  await page.getByRole('button',{name:'Insérer dans le Word'}).click();
  await page.waitForFunction(()=>!document.querySelector('dialog[open]'));
  await page.locator('[contenteditable=true]').focus();
  await page.keyboard.press('Control+End');
  await page.keyboard.press('Control+Enter');
  await page.keyboard.type('Page de la roue');
  await page.keyboard.press('Enter');
  await page.getByRole('button',{name:'Outils',exact:true}).click();
  await page.locator('dialog select[name=type]').selectOption('wheel');
  await page.getByRole('button',{name:'Insérer dans le Word'}).click();
  await page.waitForFunction(()=>!document.querySelector('dialog[open]'));
  assert.equal(await page.evaluate(()=>WordDocuments.save()),true);
  const saved = await page.evaluate(()=>lastBytes);
  const files = unzipSync(new Uint8Array(saved));
  const relationships = strFromU8(files['word/_rels/document.xml.rels']);
  assert.ok(relationships.includes('mepTool='));
  assert.ok(Object.keys(files).filter(name=>name.startsWith('word/media/')).length >= 2);
  const beforeUploads = await page.evaluate(()=>uploads);
  const positions = () => [...document.querySelectorAll('#wordDocumentEditor *')].filter(n=>n.scrollHeight>n.clientHeight+10 && n.clientHeight>100).map(n=>({cls:n.className,top:n.scrollTop}));
  const scrollBefore = await page.evaluate(positions);
  await page.getByRole('button',{name:'Présenter',exact:true}).click();
  await page.waitForSelector('.word-presentation-page [data-page-index]');
  await page.waitForSelector('.word-presentation .word-live-tool');
  await page.getByRole('button',{name:'Lancer',exact:true}).click();
  assert.ok(['Alice','Bob'].includes(await page.locator('.word-presentation .word-live-tool output').textContent()));
  await page.screenshot({path:`${root}/tests/visual/current-word-presentation-wheel.png`});
  await page.getByRole('button',{name:'← Précédente',exact:true}).click();
  await page.waitForSelector('.word-presentation [aria-label=Chronomètre]');
  assert.equal(await page.locator('.word-presentation .word-live-tool output').textContent(),'05:00');
  await page.getByRole('button',{name:'Démarrer',exact:true}).click();
  await page.waitForFunction(()=>document.querySelector('.word-presentation .word-live-tool output').textContent!=='05:00');
  await page.getByRole('button',{name:'Pause',exact:true}).click();
  await page.screenshot({path:`${root}/tests/visual/current-word-presentation-timer.png`});
  assert.equal(await page.evaluate(()=>uploads),beforeUploads,'Presentation and tools never auto-save');
  assert.equal(await page.evaluate(()=>WordDocuments.hasChanges()),false,'Presentation leaves the DOCX clean');
  await page.getByRole('button',{name:'Quitter la présentation'}).click();
  assert.deepEqual(await page.evaluate(positions),scrollBefore,'Leaving presentation restores the editor scroll');
  await page.evaluate(()=>WordDocuments.requestClose());
  const activityId = await page.evaluate(()=>state.lesson.activities.at(-1).id);
  await page.evaluate(id=>WordDocuments.present(id), activityId);
  await page.waitForSelector('.word-presentation-page [data-page-index]');
  await page.waitForSelector('.word-presentation [aria-label=Chronomètre]');
  await page.getByRole('button',{name:'Suivante →',exact:true}).click();
  await page.waitForSelector('.word-presentation [aria-label="Roue des élèves"]');
  await page.getByRole('button',{name:'Quitter la présentation'}).click();
  assert.equal(await page.getByRole('button',{name:'Enregistrer',exact:true}).count(),0,'Presentation opened from the lesson is read-only');
  await page.getByRole('button',{name:'Fermer',exact:true}).click();
  console.log('Word tools: native image/link export, timer, wheel, page navigation, presentation after reopen, no auto-save and viewport restore passed.');
}
